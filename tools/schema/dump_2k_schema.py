"""Turn the DB2K Editor's bundled offset JSON into a human-readable data dictionary.

Usage:
    python tools/schema/dump_2k_schema.py /path/to/2k26-Editor/2keditor/core/Offsets > docs/research/2k26-data-dictionary.md

Only field display names and group structure are emitted. Memory addresses are
deliberately dropped: we want the vocabulary of 2K's player and tuning model,
not a memory map.
Source project: https://github.com/discobisco/2k26-Editor (unlicensed, field
labels reproduced as facts with attribution).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

FILES = [
    ("offsets_players.json", "Players"),
    ("offsets_ai_tuning.json", "AITuning"),
    ("offsets_teams.json", "Teams"),
    ("offsets_playbook.json", "Playbook"),
]


def field_name(f: dict) -> str:
    return f.get("display_name") or f.get("normalized_name") or "?"


def versions_present(f: dict) -> str:
    v = f.get("versions") or {}
    return ",".join(sorted(k for k in v if v[k]))


def render(offsets_dir: Path, files=FILES) -> str:
    out = ["# 2K data dictionary (field names from DB2K Editor schema)", ""]
    out.append("Generated by tools/schema/dump_2k_schema.py. Names only, no addresses.")
    out.append("Source: https://github.com/discobisco/2k26-Editor (bundled offset JSON).")
    out.append("")
    for fname, top in files:
        path = offsets_dir / fname
        if not path.exists():
            continue
        data = json.loads(path.read_text())[top]
        total = sum(len(fields) for groups in data.values() for fields in groups.values())
        out.append(f"## {top} ({total} fields)")
        for section, groups in data.items():
            for group, fields in groups.items():
                names = [field_name(f) for f in fields]
                vers = {versions_present(f) for f in fields} - {""}
                vtxt = f" versions: {' | '.join(sorted(vers))}" if vers else ""
                out.append(f"### {section} / {group} ({len(names)}){vtxt}")
                out.append(", ".join(names))
                out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    print(render(Path(sys.argv[1])))
